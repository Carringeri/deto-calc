def sadovsky_dp_kpa(R_m: float, q_kg: float) -> float:
    # Параметрическое расстояние (R / кубический корень из массы в кг)
    x = R_m / (q_kg ** (1 / 3))

    # Формула Садовского для давления в МПа
    dp_mpa = 0.084 / x + 0.27 / (x ** 2) + 0.7 / (x ** 3)

    # Переводим МПа в кПа (1 МПа = 1000 кПа)
    return dp_mpa * 1000